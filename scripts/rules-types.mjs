// Regenerates the barrel file for the ts-rs generated engine types (run after `cargo test` in engine/).
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const dir = join(dirname(fileURLToPath(import.meta.url)), '../packages/shared/src/rules/generated');
const names = readdirSync(dir).filter((f) => f.endsWith('.ts') && f !== 'index.ts').map((f) => f.slice(0, -3)).sort();
writeFileSync(join(dir, 'index.ts'), '// Generated by scripts/rules-types.mjs - do not edit.\n' + names.map((n) => `export type { ${n} } from './${n}';`).join('\n') + '\n');
writeFileSync(join(dir, '../index.ts'), "export * from './generated';\n");
console.log(`${names.length} engine types`);
